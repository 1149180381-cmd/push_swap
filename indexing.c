#include "push_swap.h"

void	index_stack(t_stack *stack)
{
	t_node	*current;
	t_node	*compare;
	int		index;

	if (!stack || !stack->top)
		return ;
	current = stack->top;
	while (current)
	{
		index = 0;
		compare = stack->top;
		while (compare)
		{
			if (current->value > compare->value)
				index++;
			compare = compare->next;
		}
		current->index = index;
		current = current->next;
	}
}
